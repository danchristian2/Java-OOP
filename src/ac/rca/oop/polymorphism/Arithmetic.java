package ac.rca.oop.polymorphism;

public class Arithmetic {
    public int addition() {
        return 10 + 20;
    }
    public int addition(int a,int b) {
        return a + b;
    }
    public int addition(int a,int b,int c) {
        return a + b + c;
    }
    public double addition(double a,double b) {
        return a + b;
    }
    public double addition(double a,double b,double c) {
        return a + b + c;
    }
    public int addition(int a) {
        return a + 34;
    }
    public double addition(double a) {
        return a * 2;
    }
    public long addition(long a,long b) {
        return a + b;
    }
    public long addition(long a,long b,long c) {
        return a + b + c;
    }
    public int addition(int a,int b,int c,int d) {
        return a + b + c + d;
    }
}
